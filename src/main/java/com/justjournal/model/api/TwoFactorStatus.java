package com.justjournal.model.api;

import com.justjournal.model.TwoFactorMethod;
import java.io.Serial;
import java.io.Serializable;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * What the preferences page shows about a user's second factor.
 *
 * @author Lucas Holt
 */
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class TwoFactorStatus implements Serializable {

  @Serial private static final long serialVersionUID = -7030214489165530912L;

  private boolean enabled;

  private TwoFactorMethod method;

  /** Address a mailed code would go to, or null when none is on file. */
  private String email;

  private long recoveryCodesLeft;

  private long trustedBrowsers;
}
